#!/bin/bash
# Regenerate Agent/AuscultAgent/DeviceModels.swift from Xcode's own database.
#
# The phone only knows its hardware identifier ("iPhone14,5"), which reads as a
# different phone to anyone who is not an Apple engineer -- the first external
# tester, on an iPhone 13, was told he had an "iPhone 14,5". The mapping to
# marketing names is taken from Xcode's device_traits.db rather than typed by
# hand: a wrong name would be worse than the raw identifier, and Apple's table
# is the one devicectl itself uses. Re-run after installing a newer Xcode to
# pick up new models.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
XCODE="${XCODE:-/Applications/Xcode.app}"
DB="$XCODE/Contents/Developer/Platforms/iPhoneOS.platform/usr/standalone/device_traits.db"
OUT="$ROOT/Agent/AuscultAgent/DeviceModels.swift"
[ -f "$DB" ] || { echo "no device_traits.db under $XCODE" >&2; exit 1; }

XBUILD="$(DEVELOPER_DIR="$XCODE/Contents/Developer" xcodebuild -version | sed -n 's/^Build version //p')"
QUERY="SELECT DISTINCT ProductType, ProductDescription FROM Devices
       WHERE (ProductType LIKE 'iPhone%' OR ProductType LIKE 'iPad%')
         AND ProductDescription IS NOT NULL AND ProductDescription <> ''"

# One ProductType must never map to two names; refuse rather than guess.
CONFLICTS="$(sqlite3 "$DB" "SELECT ProductType FROM ($QUERY) GROUP BY ProductType HAVING COUNT(*) > 1")"
[ -z "$CONFLICTS" ] || { echo "conflicting names for: $CONFLICTS" >&2; exit 1; }

{
cat <<HEAD
// GENERATED by Scripts/generate-device-models.sh from Xcode $XBUILD's
// device_traits.db. Do not edit by hand -- re-run the script instead.

import Foundation

enum DeviceModels {
    /// Hardware identifier → the name Apple sells it under.
    static let names: [String: String] = [
HEAD
# Natural sort: family, then major, then minor, so iPhone9,1 precedes iPhone10,1.
sqlite3 -separator $'\t' "$DB" "$QUERY" \
  | awk -F'\t' '{ split($1, p, /[,]/); fam=p[1]; gsub(/[0-9]+$/, "", fam); maj=p[1]; sub(/^[A-Za-z]+/, "", maj);
                  printf "%s\t%06d\t%06d\t%s\t%s\n", fam, maj, p[2], $1, $2 }' \
  | sort -t$'\t' -k1,1 -k2,2n -k3,3n \
  | awk -F'\t' '{ gsub(/"/, "\\\"", $5); printf "        \"%s\": \"%s\",\n", $4, $5 }'
cat <<'TAIL'
    ]

    /// Marketing name for an identifier, or nil for a model newer than this
    /// table -- callers show the raw identifier then, which is still correct,
    /// just less friendly.
    static func name(for identifier: String) -> String? { names[identifier] }
}
TAIL
} > "$OUT"

echo "Wrote $OUT ($(grep -c '": "' "$OUT") models, from Xcode $XBUILD)"
